export interface MakefileOptions {
  lab: string;
  srcDir: string;
  lang?: Lang;
}

export function Makefile({lab, srcDir, lang = 'en'}: MakefileOptions): string {
  const t = kText[lang];
  const targets = t.targets
    .map(([target, what]) => `#   ${target.padEnd(15)} ${what}`)
    .join('\n');
  return `# ${t.makefileTitle(lab)}
#
${targets}
#
# ${t.sanitizers}

LAB      := ${lab}
SRC_DIR  := ${srcDir}
TEST_DIR := tests
BUILD    := build

ifeq ($(origin CXX),default)
  CXX := $(shell command -v clang++ >/dev/null 2>&1 && echo clang++ || echo g++)
endif
CLANG_FORMAT ?= clang-format
CLANG_TIDY   ?= clang-tidy

STD      := -std=c++20
WARNINGS := -Wall -Wextra -Wpedantic -Wshadow -Wconversion -Wsign-conversion
SAN      ?= -fsanitize=address,undefined -fno-omit-frame-pointer
CXXFLAGS ?= -O0 -g
CPPFLAGS += -I$(SRC_DIR)

# ${t.isystem}
GTEST_CFLAGS := $(patsubst -I%,-isystem%,\\
                  $(shell pkg-config --cflags gtest 2>/dev/null))
GTEST_LIBS   := $(shell pkg-config --libs gtest_main 2>/dev/null \\
                  || echo -lgtest_main -lgtest) -pthread
SYSROOT      := $(shell xcrun --show-sdk-path 2>/dev/null)
TIDY_FLAGS   := $(if $(SYSROOT),-isysroot $(SYSROOT))

EXCLUDE   := -not -path '*/$(BUILD)/*' -not -path '*/.*'
SRCS      := $(patsubst ./%,%,$(shell find $(SRC_DIR) \\
               \\( -name '*.cc' -o -name '*.cpp' \\) $(EXCLUDE) \\
               -not -path '*/$(TEST_DIR)/*' \\
               -not -name '*_test.cc' -not -name '*_test.cpp'))
TEST_SRCS := $(sort $(patsubst ./%,%,$(shell find $(SRC_DIR) $(TEST_DIR) \\
               \\( -name '*_test.cc' -o -name '*_test.cpp' \\) $(EXCLUDE) \\
               2>/dev/null)) $(wildcard $(TEST_DIR)/*.cc $(TEST_DIR)/*.cpp))
HDRS      := $(sort $(patsubst ./%,%,$(shell find $(SRC_DIR) $(TEST_DIR) \\
               \\( -name '*.h' -o -name '*.hpp' \\) $(EXCLUDE) 2>/dev/null)))
MAIN_RE   := ^[[:space:]]*int[[:space:]]+main[[:space:]]*[(]
MAIN_SRC  := $(shell grep -lE '$(MAIN_RE)' $(SRCS) /dev/null)
LIB_SRCS  := $(filter-out $(MAIN_SRC),$(SRCS))

obj = $(patsubst %,$(BUILD)/obj/%.o,$(1))
APP_OBJS  := $(call obj,$(SRCS))
TEST_OBJS := $(call obj,$(LIB_SRCS) $(TEST_SRCS))
APP       := $(BUILD)/$(LAB)
TEST_BIN  := $(BUILD)/tests

.PHONY: all run test build-tests fmt fmt-check tidy check flags clean

all: $(APP)

$(APP): $(APP_OBJS)
\t$(CXX) $(SAN) $^ -o $@ $(LDFLAGS)

build-tests: $(TEST_BIN)

$(TEST_BIN): $(TEST_OBJS)
\t$(CXX) $(SAN) $^ -o $@ $(LDFLAGS) $(GTEST_LIBS)

# ${t.abspath}
$(BUILD)/obj/%.o: %
\t@mkdir -p $(@D)
\t$(CXX) $(STD) $(WARNINGS) $(SAN) $(CXXFLAGS) $(CPPFLAGS) $(GTEST_CFLAGS) \\
\t  -MMD -MP -c $(abspath $<) -o $@

run: $(APP)
\t./$(APP) $(ARGS)

test: $(TEST_BIN)
\t./$(TEST_BIN) $(GTEST_ARGS)

fmt:
\t$(CLANG_FORMAT) -i --style=file $(SRCS) $(TEST_SRCS) $(HDRS)

fmt-check:
\t$(CLANG_FORMAT) --dry-run --Werror --style=file \\
\t  $(abspath $(SRCS) $(TEST_SRCS) $(HDRS))

tidy:
\t$(CLANG_TIDY) --quiet $(abspath $(SRCS) $(TEST_SRCS)) -- \\
\t  $(STD) $(CPPFLAGS) $(GTEST_CFLAGS) $(TIDY_FLAGS)

check: fmt-check tidy test
\t@echo "${t.checkPassed}"

flags:
\tprintf '%s\\n' -xc++ $(STD) $(WARNINGS) $(CPPFLAGS) $(GTEST_CFLAGS) \\
\t  $(TIDY_FLAGS) > compile_flags.txt

clean:
\trm -rf $(BUILD)

-include $(APP_OBJS:.o=.d) $(TEST_OBJS:.o=.d)
`;
}

export type PreCommitStep = 'format' | 'tidy';
export type PrePushStep = 'test';

export interface HookTools {
  clangFormat: string;
  clangTidy: string;
}

// Маркер, по которому отличаем свои хуки от чужих.
export const kHookMarker = 'labkit-hook';

function HookHeader(kind: string, tools: HookTools, lang: Lang): string {
  const t = kText[lang];
  const command = kind === 'pre-push' ? 'push' : 'commit';
  return `#!/usr/bin/env bash
# ${kHookMarker}: ${kind}. Generated by ITMO C++ Lab Kit.
# ${t.hookSkip} git ${command} --no-verify
set -u
CLANG_FORMAT="\${CLANG_FORMAT:-${tools.clangFormat}}"
CLANG_TIDY="\${CLANG_TIDY:-${tools.clangTidy}}"
cd "$(git rev-parse --show-toplevel)" || exit 1

# ${t.hookLocal}
local_hook="$(dirname "$0")/${kind}.local"
if [ -x "$local_hook" ]; then
  "$local_hook" "$@" || exit $?
fi
`;
}

export function PreCommitHook(
  steps: PreCommitStep[],
  tools: HookTools,
  lang: Lang = 'en',
): string {
  const t = kText[lang];
  let script = `${HookHeader('pre-commit', tools, lang)}
files=()
while IFS= read -r file; do
  files+=("$file")
done < <(git diff --cached --name-only --diff-filter=ACMR -- \\
           '*.cc' '*.cpp' '*.h' '*.hpp')
[ \${#files[@]} -eq 0 ] && exit 0
failed=0
`;
  if (steps.includes('format')) {
    script += `
# ${t.hookStaged}
# Без .clang-format в репозитории стиль не задан — формат не проверяем.
bad_format=()
for file in "\${files[@]}"; do
  [ -f .clang-format ] || [ -f _clang-format ] || break
  if ! git show ":$file" | "$CLANG_FORMAT" --style=file \\
      --assume-filename="$file" --dry-run --Werror >/dev/null 2>&1; then
    bad_format+=("$file")
  fi
done
if [ \${#bad_format[@]} -gt 0 ]; then
  echo "✘ ${t.notFormatted}"
  printf '    %s\\n' "\${bad_format[@]}"
  echo "  ${t.fix} \\"$CLANG_FORMAT\\" -i \${bad_format[*]} && git add -u"
  failed=1
fi
`;
  }
  if (steps.includes('tidy')) {
    script += `
sources=()
for file in "\${files[@]}"; do
  # Тесты обычно даёт преподаватель — clang-tidy их не трогает.
  case "$file" in
    tests/*|test/*|*_test.*|*_tests.*) ;;
    *.cc|*.cpp) sources+=("$file") ;;
  esac
done
if [ \${#sources[@]} -gt 0 ]; then
  # Пустой массив под set -u в bash 3.2 разворачиваем через \${a[@]+…}.
  if [ -f compile_commands.json ] || [ -f compile_flags.txt ]; then
    tidy_args=()
  elif [ -f build/compile_commands.json ]; then
    tidy_args=(-p build)
  else
    tidy_args=(-- -std=c++20 -I. -Isrc -Iinclude
               $(pkg-config --cflags gtest 2>/dev/null | sed 's/-I/-isystem/g'))
  fi
  echo "… clang-tidy: \${#sources[@]} ${t.tidyFiles}"
  if ! "$CLANG_TIDY" --quiet --warnings-as-errors='*' "\${sources[@]}" \\
      \${tidy_args[@]+"\${tidy_args[@]}"} 2>/dev/null; then
    echo "✘ ${t.tidyFailed}"
    failed=1
  fi
fi
`;
  }
  script += `
if [ $failed -ne 0 ]; then
  echo "${t.commitStopped} git commit --no-verify"
  exit 1
fi
echo "✔ ${t.commitPassed}"
`;
  return script;
}

export function PrePushHook(
  steps: PrePushStep[],
  tools: HookTools,
  lang: Lang = 'en',
  build_dir = 'build',
): string {
  const t = kText[lang];
  let script = HookHeader('pre-push', tools, lang);
  if (steps.includes('test')) {
    script += `
B='${build_dir.replace(/'/g, `'\\''`)}'
fail() {
  echo "✘ ${t.testsFailed} git push --no-verify"
  exit 1
}
# Наш Makefile, затем CMake, затем цель test чужого Makefile.
if [ -f Makefile ] && grep -q 'ITMO C++ Lab Kit' Makefile; then
  echo "… make test"
  make test || fail
elif [ -f CMakeLists.txt ]; then
  echo "… cmake --build $B && ctest"
  if [ ! -f "$B/CMakeCache.txt" ]; then
    cmake -S . -B "$B" -DCMAKE_EXPORT_COMPILE_COMMANDS=ON >/dev/null || fail
  fi
  jobs=$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 4)
  cmake --build "$B" --parallel || fail
  ctest --test-dir "$B" --output-on-failure --parallel "$jobs" || fail
elif [ -f Makefile ] && make -n test >/dev/null 2>&1; then
  echo "… make test"
  make test || fail
else
  echo "${t.noTestTarget}"
  exit 0
fi
echo "✔ ${t.testsPassed}"
`;
  }
  return script;
}
