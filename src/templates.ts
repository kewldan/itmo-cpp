export function ClangTidy(profile: TidyProfile, limits: Limits): string {
  const checks = profile === 'strict' ? kStrictChecks : kBasicChecks;
  const options: Array<[string, string | number]> = [
    ...kNamingOptions.map(([key, value]): [string, string] => [
      `readability-identifier-naming.${key}`,
      value,
    ]),
    [
      'readability-function-cognitive-complexity.Threshold',
      limits.maxCognitive,
    ],
    ['readability-function-size.LineThreshold', limits.maxLines],
    ['readability-function-size.ParameterThreshold', limits.maxParams],
    ['readability-function-size.NestingThreshold', limits.maxNesting],
  ];
  const lines = [
    `# Profile "${profile}". Generated by ITMO C++ Lab Kit.`,
    '---',
    'Checks: >',
    ...checks.map(
      (check, i) => `  ${check}${i + 1 < checks.length ? ',' : ''}`,
    ),
    `WarningsAsErrors: '${profile === 'strict' ? '*' : ''}'`,
    `HeaderFilterRegex: '.*'`,
    'FormatStyle: file',
    'CheckOptions:',
    ...options.map(([key, value]) => `  - { key: ${key}, value: '${value}' }`),
    '...',
    '',
  ];
  return lines.join('\n');
}

